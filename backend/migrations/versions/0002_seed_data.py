"""Load the seed dataset.

1 patient, 2 physicians, 1,201 threads and 11,447 messages carried over from
the app's original SQLite database.

The fixture is a gzipped JSONL file generated by ``scripts/build_seed.py``.
Rows are streamed in batches rather than read into one list so the migration's
memory use stays flat.

Revision ID: 0002
Revises: 0001
"""

import gzip
import json
from pathlib import Path
from typing import Any, Iterator

from alembic import op
import sqlalchemy as sa

revision = "0002"
down_revision = "0001"
branch_labels = None
depends_on = None

FIXTURE = Path(__file__).resolve().parents[2] / "fixtures" / "seed.jsonl.gz"
BATCH_SIZE = 2000

INSERTS = {
    "patient": "INSERT INTO patients (id, name) VALUES (:id, :name)",
    "physician": "INSERT INTO physicians (id, name) VALUES (:id, :name)",
    "thread": (
        "INSERT INTO threads (id, title, date_created, patient_id)"
        " VALUES (:id, :title, :date_created, :patient_id)"
    ),
    "thread_physician": (
        "INSERT INTO threads_physicians (thread_id, physician_id)"
        " VALUES (:thread_id, :physician_id)"
    ),
    "message": (
        "INSERT INTO messages"
        " (id, thread_id, author_patient_id, author_physician_id,"
        "  message, timestamp, msg_index)"
        " VALUES (:id, :thread_id, :author_patient_id, :author_physician_id,"
        "         :message, :timestamp, :msg_index)"
    ),
}


def _read_fixture() -> Iterator[dict[str, Any]]:
    with gzip.open(FIXTURE, "rt", encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                yield json.loads(line)


def upgrade() -> None:
    connection = op.get_bind()

    # The fixture is ordered so that a row's referents always precede it, so a
    # batch can be flushed as soon as the record kind changes.
    pending_kind: str | None = None
    pending: list[dict[str, Any]] = []

    def flush() -> None:
        if pending and pending_kind is not None:
            connection.execute(sa.text(INSERTS[pending_kind]), pending)
        pending.clear()

    for record in _read_fixture():
        kind = record.pop("kind")
        if kind != pending_kind:
            flush()
            pending_kind = kind
        pending.append(record)
        if len(pending) >= BATCH_SIZE:
            flush()
    flush()

    # `messages.id` values come from the fixture, so the BIGSERIAL sequence is
    # still at 1. Fast-forward it or the first application insert collides.
    connection.execute(
        sa.text(
            "SELECT setval("
            "  pg_get_serial_sequence('messages', 'id'),"
            "  COALESCE((SELECT MAX(id) FROM messages), 1)"
            ")"
        )
    )


def downgrade() -> None:
    connection = op.get_bind()
    for table in ("messages", "threads_physicians", "threads", "physicians", "patients"):
        connection.execute(sa.text(f"DELETE FROM {table}"))
