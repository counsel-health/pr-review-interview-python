"""
Alembic environment.

Migrations run over the same async engine the application uses, against
whatever database ``app/db.py`` resolves — the embedded PostgreSQL server by
default, or ``DATABASE_URL`` when that is set.

Revisions here are written by hand rather than autogenerated: the schema is
meant to read as a history of deliberate changes, and ``app/schema.py`` is the
query-building view of the result.
"""

import asyncio
from logging.config import fileConfig

from alembic import context
from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from app.db import resolve_database_url
from app.schema import metadata_obj

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

# configparser treats % as an interpolation marker.
config.set_main_option("sqlalchemy.url", resolve_database_url().replace("%", "%%"))

target_metadata = metadata_obj


def run_migrations_offline() -> None:
    context.configure(
        url=config.get_main_option("sqlalchemy.url"),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    context.configure(connection=connection, target_metadata=target_metadata)
    with context.begin_transaction():
        context.run_migrations()


async def run_migrations_online() -> None:
    engine = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    async with engine.connect() as connection:
        await connection.run_sync(do_run_migrations)
    await engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_migrations_online())
