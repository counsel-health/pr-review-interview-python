"""
Load the seed dataset: 1 patient, 2 physicians, 1,201 threads and 11,447
messages carried over from the app's pre-Django SQLite database.

The fixture is a gzipped JSONL file generated by ``scripts/build_seed.py``.
Rows are streamed in ``bulk_create`` batches rather than read into one list so
the migration's memory use stays flat.
"""

import gzip
import json
from pathlib import Path
from typing import Any, Iterator

from django.db import migrations

FIXTURE = Path(__file__).resolve().parent.parent / "fixtures" / "seed.jsonl.gz"
BATCH_SIZE = 2000


def _read_fixture() -> Iterator[dict[str, Any]]:
    with gzip.open(FIXTURE, "rt", encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                yield json.loads(line)


def load_seed(apps, schema_editor):
    Patient = apps.get_model("core", "Patient")
    Physician = apps.get_model("core", "Physician")
    Thread = apps.get_model("core", "Thread")
    ThreadPhysician = apps.get_model("core", "ThreadPhysician")
    Message = apps.get_model("core", "Message")

    builders = {
        "patient": (Patient, lambda r: Patient(id=r["id"], name=r["name"])),
        "physician": (Physician, lambda r: Physician(id=r["id"], name=r["name"])),
        "thread": (
            Thread,
            lambda r: Thread(
                id=r["id"],
                title=r["title"],
                date_created=r["date_created"],
                patient_id=r["patient_id"],
            ),
        ),
        "thread_physician": (
            ThreadPhysician,
            lambda r: ThreadPhysician(
                thread_id=r["thread_id"], physician_id=r["physician_id"]
            ),
        ),
        "message": (
            Message,
            lambda r: Message(
                id=r["id"],
                thread_id=r["thread_id"],
                author_patient_id=r["author_patient_id"],
                author_physician_id=r["author_physician_id"],
                message=r["message"],
                timestamp=r["timestamp"],
                msg_index=r["msg_index"],
            ),
        ),
    }

    # The fixture is ordered so that a row's referents always precede it, so a
    # batch can be flushed as soon as the record kind changes.
    pending_kind: str | None = None
    pending: list[Any] = []

    def flush() -> None:
        if pending and pending_kind is not None:
            builders[pending_kind][0].objects.bulk_create(pending, batch_size=BATCH_SIZE)
        pending.clear()

    for record in _read_fixture():
        kind = record["kind"]
        if kind != pending_kind:
            flush()
            pending_kind = kind
        pending.append(builders[kind][1](record))
        if len(pending) >= BATCH_SIZE:
            flush()
    flush()

    # `messages.id` values come from the fixture, so the BIGSERIAL sequence is
    # still at 1. Fast-forward it or the first application insert collides.
    with schema_editor.connection.cursor() as cursor:
        cursor.execute(
            "SELECT setval("
            "  pg_get_serial_sequence('messages', 'id'),"
            "  COALESCE((SELECT MAX(id) FROM messages), 1)"
            ")"
        )


def unload_seed(apps, schema_editor):
    for model_name in ("Message", "ThreadPhysician", "Thread", "Physician", "Patient"):
        apps.get_model("core", model_name).objects.all().delete()


class Migration(migrations.Migration):

    dependencies = [
        ("core", "0001_initial"),
    ]

    operations = [
        migrations.RunPython(load_seed, unload_seed),
    ]
